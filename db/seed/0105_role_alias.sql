BEGIN TRY
    DECLARE @src TABLE
    (
        alias_name nvarchar(64) NOT NULL PRIMARY KEY,
        role_name nvarchar(64) NOT NULL,
        is_assumption bit NOT NULL,
        related_question nvarchar(40) NULL,
        note nvarchar(400) NULL
    );
    INSERT INTO @src (alias_name, role_name, is_assumption, related_question, note) VALUES
        (N'Operations-IOC - NMD', N'Operations-IOC', 1, N'Q-496', N'Working assumption WA-02 [INFERRED]: the client file uses "Operations-IOC - NMD" in approval routes (responsible on R2 [REF-46:L0211]; responsible on R3 [REF-46:L0212]; responsible on R4 [REF-46:L0213]; responsible on R5 [REF-46:L0214]) but defines no such role in Role Definitions; read as "Operations-IOC". Awaiting the client answer to Q-496.');   -- 4 uses in routes, first R2 [REF-46:L0211]

    DECLARE @n_updated int = 0, @n_new int = 0, @n_source int = (SELECT COUNT(*) FROM @src);

    BEGIN TRANSACTION;
    UPDATE t SET
            t.role_name = s.role_name,
            t.is_assumption = s.is_assumption,
            t.related_question = s.related_question,
            t.note = s.note
    FROM app.role_alias AS t
    JOIN @src AS s ON s.alias_name = t.alias_name
    WHERE EXISTS (SELECT s.role_name, s.is_assumption, s.related_question, s.note EXCEPT SELECT t.role_name, t.is_assumption, t.related_question, t.note);
    SET @n_updated = @@ROWCOUNT;

    INSERT INTO app.role_alias (alias_name, role_name, is_assumption, related_question, note)
    SELECT s.alias_name, s.role_name, s.is_assumption, s.related_question, s.note
    FROM @src AS s
    WHERE NOT EXISTS (SELECT 1 FROM app.role_alias AS t WHERE t.alias_name = s.alias_name);
    SET @n_new = @@ROWCOUNT;
    COMMIT TRANSACTION;

    PRINT 'OK  0105 loaded: ' + CAST(@n_source AS varchar(12)) + ' aliases (' + CAST(@n_new AS varchar(12)) + ' new, ' + CAST(@n_updated AS varchar(12)) + ' updated)';
END TRY
