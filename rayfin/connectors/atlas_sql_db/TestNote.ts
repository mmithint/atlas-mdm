import { entity, int, text, date, role } from '@microsoft/rayfin-core';
import { Source } from '@microsoft/rayfin-connectors';
import type { AutoGenerated } from '@microsoft/rayfin-connectors';

// Authenticated users can read and add notes (no update/delete from the app).
@role('authenticated', ['read', 'create'])
@entity()
export class TestNote extends Source({
    schema: 'dbo',
    table: 'TestNote',
    primaryKey: ['id'],
}) {
    // IDENTITY column: never send it on create.
    @int({ column: 'id' })
    id!: AutoGenerated<number>;

    @text({ column: 'title', max: 200 })
    title!: string;

    @text({ column: 'createdBy', optional: true, max: 320 })
    createdBy?: string;

    @date({ column: 'createdAt', optional: true })
    createdAt?: Date;
}
